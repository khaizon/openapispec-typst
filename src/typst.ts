import type { Dict } from "./spec.js";

const IDENT = /^[A-Za-z_][A-Za-z0-9_-]*$/;
const KEYWORDS = new Set([
  "none", "auto", "true", "false", "let", "set", "show", "if", "else", "for",
  "in", "import", "include", "context", "return", "break", "continue", "while",
  "as", "and", "or", "not",
]);

function isScalar(value: any): boolean {
  return value === null || typeof value === "boolean" || typeof value === "number" || typeof value === "string";
}

function encodeString(value: string): string {
  const chunks: string[] = ['"'];
  for (const char of value) {
    const code = char.codePointAt(0)!;
    if (char === "\\") chunks.push("\\\\");
    else if (char === '"') chunks.push('\\"');
    else if (char === "\n") chunks.push("\\n");
    else if (char === "\r") chunks.push("\\r");
    else if (char === "\t") chunks.push("\\t");
    else if (code < 0x20) chunks.push("\\u{" + code.toString(16) + "}");
    else chunks.push(char);
  }
  chunks.push('"');
  return chunks.join("");
}

function encodeKey(key: string): string {
  if (IDENT.test(key) && !KEYWORDS.has(key)) return key;
  return encodeString(key);
}

export function encode(value: any, indent = 0): string {
  if (value === null || value === undefined) return "none";
  if (value === true) return "true";
  if (value === false) return "false";
  if (typeof value === "string") return encodeString(value);
  if (typeof value === "number") {
    if (!Number.isFinite(value)) return "0.0";
    return Number.isInteger(value) ? String(value) : String(value);
  }
  const pad = "  ".repeat(indent);
  const childPad = "  ".repeat(indent + 1);
  if (Array.isArray(value)) {
    if (value.length === 0) return "()";
    if (value.every(isScalar)) {
      const inline = value.map((item) => encode(item, indent + 1)).join(", ");
      if (inline.length <= 72) return "(" + inline + ",)";
    }
    const body = value.map((item) => childPad + encode(item, indent + 1)).join(",\n");
    return "(\n" + body + ",\n" + pad + ")";
  }
  if (typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "()";
    const body = entries
      .map(([key, item]) => childPad + encodeKey(key) + ": " + encode(item, indent + 1))
      .join(",\n");
    return "(\n" + body + ",\n" + pad + ")";
  }
  throw new TypeError("cannot encode " + typeof value + " as Typst");
}

export function typstDocument(spec: Dict, banner = "Generated by the TypeScript converter. Do not edit."): string {
  return (
    "// " + banner + "\n" +
    "// Data is normalised in src/model.ts.\n" +
    "#let spec = " + encode(spec) + "\n"
  );
}
